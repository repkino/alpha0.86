function grad1(hash, x) {
    const h = hash & 0x0F;
    let grad = 1 + (h & 7);
    if (h & 8) grad = -grad;
    return grad * x;
}

// 1D-симплекс: формула идентична экземпляру оригинального плагина (Simplex1)
function noise1D(x) {
    const i0 = Math.floor(x);
    const i1 = i0 + 1.0;
    const x0 = x - i0;
    const x1 = x0 - 1.0;

    let t0 = 1.0 - x0 * x0;
    t0 *= t0;
    const n0 = t0 * t0 * grad1(P[i0 & 255], x0);

    let t1 = 1.0 - x1 * x1;
    t1 *= t1;
    const n1 = t1 * t1 * grad1(P[i1 & 255], x1);

    return 0.395 * (n0 + n1);
}

const Simplex = {
    _phase: {},   // uid → накопленная позиция шума

    tick() {
        const fam = runtime.families.find(f => f.name === 'simplex');
        if (!fam) return;
        const dt = runtime.dt;
        if (dt <= 0) return;

        let active = 0;
        for (const ot of fam.members) {
            const instances = runtime.objects[ot.name].instances();
            for (const o of instances) {
                if (!o.instVars.simplexRun) continue;
                active++;

                let ph = this._phase[o.uid];
                if (ph === undefined) {
                    // Детерминированный сдвиг фазы, чтобы разные инстансы не шумели синхронно
                    ph = o.uid % 997;
                }
                ph += o.instVars.increment * dt;
                this._phase[o.uid] = ph;

                o.instVars.simValue = noise1D(ph) * o.instVars.magnitude;
            }
        }

        // Оптимизация: флаг ни у кого не включён — чистим кэш и выходим
        if (active === 0) this._phase = {};
    }
};
